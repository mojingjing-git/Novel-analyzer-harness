def _p95(values: list[float]) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    idx = min(len(s) - 1, max(0, int(len(s) * 0.95 + 0.9999) - 1))
    return round(s[idx], 3)


def summarize_split(split_name: str, work_reports: list[dict[str, Any]]) -> dict[str, Any]:
    tot_reg = sum(w["registration_total"] for w in work_reports)
    tot_res = sum(w["resolution_total"] for w in work_reports)
    tot_res_cross = sum(w.get("resolution_cross_chapter_total", w["resolution_total"]) for w in work_reports)
    tot_res_intra = sum(w.get("resolution_intra_subchapter_total", 0) for w in work_reports)
    tot_obs = tot_reg + tot_res

    def _agg(arm_key: str) -> dict[str, Any]:
        raw_reg = sum(w[arm_key]["raw_extracted_registration"] for w in work_reports)
        pv_reg = sum(w[arm_key]["prompt_view_registration_kept"] for w in work_reports)
        led_reg = sum(w[arm_key]["ledger_registration_kept"] for w in work_reports)
        amb_reg = sum(w[arm_key].get("ambiguous_registration_flagged", 0) for w in work_reports)
        raw_res = sum(w[arm_key]["raw_extracted_resolution"] for w in work_reports)
        res_setup_reg = sum(w[arm_key].get("resolution_setup_registered_in_ledger", 0) for w in work_reports)
        res_trig_unv = sum(w[arm_key].get("resolution_recheck_triggered_unverified", 0) for w in work_reports)
        rec_res = sum(w[arm_key]["resolution_recalled"] for w in work_reports)
        amb_res = sum(w[arm_key].get("ambiguous_resolution_flagged", 0) for w in work_reports)
        fa = sum(w[arm_key]["unsupported_accepts"] for w in work_reports)
        calls = sum(w[arm_key]["recheck_calls"] for w in work_reports)
        atts = sum(w[arm_key]["recheck_attempts"] for w in work_reports)
        fails = sum(w[arm_key]["recheck_failures"] for w in work_reports)
        toks = sum(w[arm_key]["recheck_tokens"] for w in work_reports)
        secs = round(sum(w[arm_key]["recheck_seconds"] for w in work_reports), 3)
        lats = [lat for w in work_reports for lat in w[arm_key]["recheck_latencies"]]
        peak_mem = max(w[arm_key]["peak_memory_bytes"] for w in work_reports)

        om_tot = sum(w[arm_key]["omission_attribution"]["reference_omissions_total"] for w in work_reports)
        om_unm = sum(w[arm_key]["omission_attribution"]["reference_omissions_unmatched"] for w in work_reports)
        by_cat: dict[str, int] = {}
        for w in work_reports:
            for k, v in (w[arm_key]["omission_attribution"]["reference_by_category"] or {}).items():
                by_cat[k] = by_cat.get(k, 0) + v

        return {
            "raw_extracted_registration": raw_reg,
            "raw_extracted_registration_rate": round(raw_reg / tot_reg, 4),
            "prompt_view_registration_kept": pv_reg,
            "prompt_view_registration_recall": round(pv_reg / tot_reg, 4),
            "ledger_registration_kept": led_reg,
            "ledger_registration_recall": round(led_reg / tot_reg, 4),
            "ambiguous_registration_flagged": amb_reg,
            "raw_extracted_resolution": raw_res,
            "raw_extracted_resolution_rate": round(raw_res / tot_res, 4),
            "resolution_setup_registered_in_ledger": res_setup_reg,
            "resolution_recheck_triggered_unverified": res_trig_unv,
            "resolution_recalled": rec_res,
            "resolution_recall": round(rec_res / tot_res, 4),
            "resolution_cross_chapter_recall": round(rec_res / max(tot_res_cross, 1), 4),
            "ambiguous_resolution_flagged": amb_res,
            "same_layer_prompt_combined_recalled": pv_reg + rec_res,
            "same_layer_prompt_combined_recall": round((pv_reg + rec_res) / tot_obs, 4),
            "same_layer_ledger_combined_recalled": led_reg + rec_res,
            "same_layer_ledger_combined_recall": round((led_reg + rec_res) / tot_obs, 4),
            "unsupported_accepts": fa,
            "recheck_calls": calls,
            "recheck_attempts": atts,
            "recheck_failures": fails,
            "recheck_failure_rate": round(fails / max(calls, 1), 4),
            "recheck_tokens": toks,
            "recheck_seconds_sum": secs,
            "recheck_p95_latency_seconds": _p95(lats),
            "peak_memory_bytes": peak_mem,
            "reference_omissions_total": om_tot,
            "reference_omissions_unmatched": om_unm,
            "reference_attribution_rate": round((om_tot - om_unm) / max(om_tot, 1), 4),
            "reference_omissions_by_category": by_cat,
        }

    b_agg = _agg("baseline")
    f_agg = _agg("repaired")

    prompt_deltas = [
        round(
            w["repaired"]["same_layer_prompt_combined_recall"]
            - w["baseline"]["same_layer_prompt_combined_recall"],
            4,
        )
        for w in work_reports
    ]
    ledger_deltas = [
        round(
            w["repaired"]["same_layer_ledger_combined_recall"]
            - w["baseline"]["same_layer_ledger_combined_recall"],
            4,
        )
        for w in work_reports
    ]

    return {
        "split": split_name,
        "works_count": len(work_reports),
        "registration_total": tot_reg,
        "resolution_total": tot_res,
        "resolution_cross_chapter_total": tot_res_cross,
        "resolution_intra_subchapter_total": tot_res_intra,
        "total_observations": tot_obs,
        "baseline": b_agg,
        "repaired": f_agg,
        "same_layer_prompt_deltas": {
            "registration_recall_delta": round(
                f_agg["prompt_view_registration_recall"] - b_agg["prompt_view_registration_recall"], 4
            ),
            "resolution_recall_delta": round(
                f_agg["resolution_recall"] - b_agg["resolution_recall"], 4
            ),
            "combined_recall_delta": round(
                f_agg["same_layer_prompt_combined_recall"] - b_agg["same_layer_prompt_combined_recall"], 4
            ),
            "works_improved_or_steady_rate": round(
                sum(1 for d in prompt_deltas if d >= 0) / len(prompt_deltas), 4
            ),
            "worst_single_work_recall_delta": min(prompt_deltas),
        },
        "same_layer_ledger_deltas": {
            "registration_recall_delta": round(
                f_agg["ledger_registration_recall"] - b_agg["ledger_registration_recall"], 4
            ),
            "resolution_recall_delta": round(
                f_agg["resolution_recall"] - b_agg["resolution_recall"], 4
            ),
            "combined_recall_delta": round(
                f_agg["same_layer_ledger_combined_recall"] - b_agg["same_layer_ledger_combined_recall"], 4
            ),
            "works_improved_or_steady_rate": round(
                sum(1 for d in ledger_deltas if d >= 0) / len(ledger_deltas), 4
            ),
            "worst_single_work_recall_delta": min(ledger_deltas),
        },
        "cost_comparison": {
            "recheck_calls_baseline": b_agg["recheck_calls"],
            "recheck_calls_repaired": f_agg["recheck_calls"],
            "recheck_calls_delta_ratio": round(
                (f_agg["recheck_calls"] - b_agg["recheck_calls"]) / max(b_agg["recheck_calls"], 1), 4
            ),
            "recheck_tokens_baseline": b_agg["recheck_tokens"],
            "recheck_tokens_repaired": f_agg["recheck_tokens"],
            "recheck_tokens_delta_ratio": round(
                (f_agg["recheck_tokens"] - b_agg["recheck_tokens"]) / max(b_agg["recheck_tokens"], 1), 4
            ),
            "recheck_seconds_baseline": b_agg["recheck_seconds_sum"],
            "recheck_seconds_repaired": f_agg["recheck_seconds_sum"],
            "recheck_seconds_delta_ratio": round(
                (f_agg["recheck_seconds_sum"] - b_agg["recheck_seconds_sum"])
                / max(b_agg["recheck_seconds_sum"], 0.001),
                4,
            ),
            "p95_latency_baseline_s": b_agg["recheck_p95_latency_seconds"],
            "p95_latency_repaired_s": f_agg["recheck_p95_latency_seconds"],
            "peak_memory_baseline_bytes": b_agg["peak_memory_bytes"],
            "peak_memory_repaired_bytes": f_agg["peak_memory_bytes"],
        },
    }


