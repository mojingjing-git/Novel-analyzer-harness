        total_call_stats["logical_calls"] += 1
        resp = await asyncio.wait_for(
            client.chat_auto(messages=[{"role": "user", "content": prompt}], max_tokens=16384),
            timeout=110,
        )
        att = int(getattr(resp, "attempts", 1) or 1)
        total_call_stats["attempts"] += att
        tok = getattr(resp, "tokens", 0)
        tok_sum = sum(int(x or 0) for x in tok) if isinstance(tok, (tuple, list)) else int(tok or 0)
        total_call_stats["tokens"] += tok_sum
        ok = bool(getattr(resp, "success", True))
