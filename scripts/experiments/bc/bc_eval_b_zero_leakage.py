def split_natural_subchapters(packets: list[dict[str, Any]], target_chars: int = 2000) -> tuple[dict[int, str], dict[str, list[tuple[int, int, int]]]]:
    """Split each packet's raw text into natural ~2000-char subchapters at paragraph/sentence boundaries.
    Takes ONLY `packets` (no reference observations, no synthetic filler chapters).
    Returns:
      - `chapters`: `{ch_num: raw_text}`
      - `packet_spans`: `{sample_id: [(ch_num, start_offset, end_offset), ...]}`
    """
    chapters: dict[int, str] = {}
    packet_spans: dict[str, list[tuple[int, int, int]]] = {}
    ch_cursor = 1

    for pkt in packets:
        sid = pkt["sample_id"]
        txt = pkt["text"]
        n = len(txt)
        spans: list[tuple[int, int, int]] = []
        pos = 0
        while pos < n:
            if n - pos <= int(target_chars * 1.35):
                end = n
            else:
                target = pos + target_chars
                # Find nearest natural paragraph or sentence break around target
                window = txt[target - 250 : min(n, target + 250)]
                rel_nl = window.find("\n")
                if rel_nl >= 0:
                    end = (target - 250) + rel_nl + 1
                else:
                    rel_p = max(window.find("。"), window.find("！"), window.find("？"))
                    end = ((target - 250) + rel_p + 1) if rel_p >= 0 else target
            ch_num = ch_cursor
            ch_cursor += 1
            chapters[ch_num] = txt[pos:end]
            spans.append((ch_num, pos, end))
            pos = end
        packet_spans[sid] = spans

    return chapters, packet_spans


