export function mergeSettingsSchema(remote?: ConfigSchemaDto | null): ConfigSchemaDto {
  if (!remote || !Array.isArray(remote.fields) || !Array.isArray(remote.groups) || remote.fields.length === 0) {
    return DEFAULT_SETTINGS_SCHEMA
  }
  const seenPaths = new Set(remote.fields.map((f) => f.path))
  const mergedFields: ConfigFieldSchemaDto[] = [
    ...remote.fields,
    ...DEFAULT_SETTINGS_SCHEMA.fields.filter((f) => !seenPaths.has(f.path)),
  ]
  const seenGroups = new Set(remote.groups.map((g) => g.id))
  const mergedGroups: ConfigGroupSchemaDto[] = [
    ...remote.groups,
    ...DEFAULT_SETTINGS_SCHEMA.groups.filter((g) => !seenGroups.has(g.id)),
  ]
  return {
    total_fields: mergedFields.length,
    groups: mergedGroups,
    fields: mergedFields,
  }
}

export function cloneSchemaDefault(spec: ConfigFieldSchemaDto): unknown {
  if (Array.isArray(spec.default)) return [...spec.default]
  if (spec.default && typeof spec.default === 'object') return { ...(spec.default as Record<string, unknown>) }
  return spec.default
}

export function buildDefaultAppConfig(): AppConfigDto {
  const out: Record<string, unknown> = { api: {}, analysis: {}, gui: {} }
  for (const spec of DEFAULT_SETTINGS_SCHEMA.fields) {
    const val = cloneSchemaDefault(spec)
    if (spec.section === 'root') {
      out[spec.key] = val
    } else {
      const sec = (out[spec.section] as Record<string, unknown>) || {}
      sec[spec.key] = val
      out[spec.section] = sec
    }
  }
  return out as AppConfigDto
}

export function getConfigValueByPath(cfg: AppConfigDto | null | undefined, spec: ConfigFieldSchemaDto): unknown {
  if (!cfg) return cloneSchemaDefault(spec)
  if (spec.section === 'root') {
    const v = (cfg as Record<string, unknown>)[spec.key]
    return v === undefined ? cloneSchemaDefault(spec) : v
  }
  const sec = (cfg as Record<string, unknown>)[spec.section]
  if (sec && typeof sec === 'object' && !Array.isArray(sec)) {
    const v = (sec as Record<string, unknown>)[spec.key]
    return v === undefined ? cloneSchemaDefault(spec) : v
  }
  return cloneSchemaDefault(spec)
}

export function setConfigValueByPath(cfg: AppConfigDto, spec: ConfigFieldSchemaDto, value: unknown): void {
  if (spec.section === 'root') {
    ;(cfg as Record<string, unknown>)[spec.key] = value
    return
  }
  const root = cfg as Record<string, unknown>
  if (!root[spec.section] || typeof root[spec.section] !== 'object' || Array.isArray(root[spec.section])) {
    root[spec.section] = {}
  }
  ;(root[spec.section] as Record<string, unknown>)[spec.key] = value
}

export function isFieldModified(cfg: AppConfigDto | null | undefined, spec: ConfigFieldSchemaDto): boolean {
  if (!cfg) return false
  const cur = getConfigValueByPath(cfg, spec)
  const defVal = spec.default
  if (Array.isArray(defVal) || (defVal && typeof defVal === 'object')) {
    try {
      return JSON.stringify(cur) !== JSON.stringify(defVal)
    } catch {
      return cur !== defVal
    }
  }
  return cur !== defVal
}

export function resetFieldToDefault(cfg: AppConfigDto, spec: ConfigFieldSchemaDto): void {
  setConfigValueByPath(cfg, spec, cloneSchemaDefault(spec))
}
